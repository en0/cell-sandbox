@final
class GolSimulation(LifeSimulation):

    def __init__(self):
        self._index = 0
        self._generation = 0
        self._prev: frozenset[Vec2] = frozenset()
        self._alive: frozenset[Vec2] = frozenset()
        self._died: frozenset[Vec2] = frozenset()
        self._born: frozenset[Vec2] = frozenset()
        self._palet = _STATE_TO_COLOR

    @override
    def reload(self, preset: int | None = None) -> int:
        # Only change if its valid.
        # If none given, change to the current (just a reset)
        if preset is not None:
            if 0 <= preset < len(_PRESETS):
                self._index = preset
            else:
                return -1

        _, self._alive = _PRESETS[self._index]

        # Reset all the lifecycle states
        self._died = frozenset()
        self._born = frozenset()
        self._prev = self._alive

        self._generation = 0
        return self._index

    @override
    def update_step(self) -> int:
        if len(self._alive) == 0:
            return self._generation

        # Scatter Count
        # iterate over each cell and incrent the value of the neighbor cells
        counts: dict[Vec2, int] = {}
        for cell in self._alive:
            for neighbor in (cell+n for n in _NEIGHBORS):
                count = counts.get(neighbor, 0)
                counts[neighbor] = count + 1

        self._alive = frozenset(
            k for k, v in counts.items()
            if (k not in self._alive and v == 3) or (k in self._alive and (1 < v < 4))
        )

        self._died = self._prev - self._alive
        self._born = self._alive - self._prev
        self._prev = self._alive

        self._generation += 1
        return self._generation

    @override
    def collect(self) -> frozenset[Vec2Like]:
        return self._alive

    @override
    def get_digest(self) -> SimulationDigest:
        preset_name, _ = _PRESETS[self._index]
        return SimulationDigest(
            generation=self._generation,
            preset=preset_name,
            alive=len(self._alive),
            born=len(self._born),
            died=len(self._died),
        )

    @override
    def get_color(self, cell: Vec2Like) -> tuple[int, int, int, int] | None:
        if cell in self._died:
            return self._palet[_STATE_DIED]
        elif cell in self._born:
            return self._palet[_STATE_BORN]
        elif cell in self._alive:
            return self._palet[_STATE_ALIVE]
        return None

    @override
    def set_debug(self, dbg: bool) -> None:
        self._palet = _STATE_TO_COLOR_DEBUG if dbg else _STATE_TO_COLOR
